/** "employee.terminated" → "Terminated an employee"; unknown actions get a tidy fallback ("Payroll: run exported"). */
export function auditActionLabel(action: string): string {
  const known = AUDIT_ACTION_LABELS[action];
  if (known) return known;
  const [area, ...rest] = action.split('.');
  const what = rest.join(' ').replace(/_/g, ' ');
  const nice = (area ?? '').replace(/_/g, ' ');
  return what ? `${nice.charAt(0).toUpperCase()}${nice.slice(1)}: ${what}` : action;
}
